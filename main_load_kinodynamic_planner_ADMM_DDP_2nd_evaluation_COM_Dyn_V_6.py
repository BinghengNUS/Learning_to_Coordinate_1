    Rl_k        = np.asarray(sysm.q_2_rotation(ql_k), dtype=np.float64)
    rl_k        = Rot.from_matrix(Rl_k)
    eulerl_k    = np.reshape(rl_k.as_euler('zyx',degrees=True),(3,1))
    Eulerl[:,k:k+1] = eulerl_k

