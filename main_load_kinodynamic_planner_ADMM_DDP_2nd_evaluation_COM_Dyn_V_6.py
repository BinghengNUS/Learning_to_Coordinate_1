pob1, pob2 = np.array([[0,height +height2+2*rq+ro]]).T, np.array([[0,height-rq-ro]]).T # [y,z] 4.18 is the limit, yielding the same height margin (0.25cm) as in Dr. Sun Sihao's paper.
